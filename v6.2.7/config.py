# 🆕 시간대별 동적 설정
# ============================================================================
def get_time_based_thresholds():
    """
    시간대별 필터 조건 반환
    
    Returns:
        dict: 현재 시간대에 맞는 설정
    """
    now = datetime.now().time()
    
    # 오전 (09:05-10:30): 보수적
    if now < datetime.strptime("10:30", "%H:%M").time():
        return {
            'min_strength': 110,
            'min_vol_ratio': 250.0,
            'min_price_change': 2.0,
            'min_consistent_seconds': 4,
            'score_threshold': 70,
        }
    
    # 정오 (10:30-13:00): 표준
    elif now < datetime.strptime("13:00", "%H:%M").time():
        return {
            'min_strength': 105,
            'min_vol_ratio': 220.0,
            'min_price_change': 1.8,
            'min_consistent_seconds': 3,
            'score_threshold': 60,
        }
    
